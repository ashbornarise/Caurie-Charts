-- Agents de contrôle : constats de chaque nuit (corrigés automatiquement ou à traiter). Ajout seulement.
CREATE TABLE IF NOT EXISTS agent_findings (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ran_at   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    agent    VARCHAR(40)  NOT NULL,
    level    VARCHAR(10)  NOT NULL,       -- corrige, alerte, info
    message  VARCHAR(600) NOT NULL,
    link     VARCHAR(300) NULL
);
