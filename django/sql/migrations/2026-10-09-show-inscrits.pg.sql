-- Monthly Show : les personnes qui demandent un rappel avant le direct (page /show). Ajout seulement.
-- Une adresse ne s'inscrit qu'une fois par émission (show_key = mois du classement révélé, ex. 2026-10).
CREATE TABLE IF NOT EXISTS show_leads (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_key     VARCHAR(10)  NOT NULL,
    name         VARCHAR(100) NOT NULL,
    email        VARCHAR(190) NOT NULL,
    country_code VARCHAR(2)   NULL,
    prediction   VARCHAR(200) NULL,          -- pronostic libre : « qui sera N°1 en Afrique de l'Ouest ? »
    locale       VARCHAR(2)   NOT NULL DEFAULT 'fr',
    ip_hash      VARCHAR(64)  NOT NULL,
    reminded_at  TIMESTAMP(0) NULL,          -- rappel envoyé le jour J
    created_at   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uq_show_lead UNIQUE (show_key, email)
);
CREATE INDEX IF NOT EXISTS ix_show_leads_key ON show_leads (show_key, created_at);
