-- Analyses : statistiques des publications, vues du site (anonymes, agrégées), historique des nuits. Ajouts seulement.
CREATE TABLE IF NOT EXISTS post_metrics (
    buffer_post_id  VARCHAR(40)  NOT NULL,
    captured_on     DATE         NOT NULL,
    social_post_id  INTEGER      NULL,            -- post Cauri d'origine (quand il est connu)
    channel         VARCHAR(20)  NOT NULL,        -- instagram, facebook, tiktok
    post_type       VARCHAR(20)  NULL,            -- post, reel, story
    sent_at         TIMESTAMP(0) NULL,
    metrics         TEXT         NOT NULL,        -- JSON : vues, portée, réactions, commentaires, partages, enregistrements…
    text_start      VARCHAR(300) NULL,
    PRIMARY KEY (buffer_post_id, captured_on)
);
CREATE TABLE IF NOT EXISTS page_views (
    day        DATE         NOT NULL,
    path       VARCHAR(200) NOT NULL,
    referrer   VARCHAR(100) NOT NULL DEFAULT '',  -- domaine d'origine seulement (google.com, instagram.com…)
    views      INTEGER      NOT NULL DEFAULT 0,
    PRIMARY KEY (day, path, referrer)
);
CREATE TABLE IF NOT EXISTS pipeline_runs (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ran_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    seconds   INTEGER      NOT NULL,
    failed    INTEGER      NOT NULL,
    steps     TEXT         NOT NULL                -- JSON : [étape, réussie, secondes]
);
