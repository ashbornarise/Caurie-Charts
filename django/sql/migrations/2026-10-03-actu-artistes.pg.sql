-- Actualité des artistes : sorties détectées sur Deezer et faits ajoutés par la rédaction (avec leur source). Ajout seulement.
CREATE TABLE IF NOT EXISTS artist_events (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id   INTEGER      NOT NULL REFERENCES artists(id),
    kind        VARCHAR(20)  NOT NULL,          -- album, ep, single, concert, clip, distinction, autre
    title       VARCHAR(200) NOT NULL,
    event_date  DATE         NOT NULL,
    summary     VARCHAR(500) NULL,
    image_url   VARCHAR(500) NULL,
    source_name VARCHAR(100) NULL,
    source_url  VARCHAR(500) NULL,
    origin      VARCHAR(10)  NOT NULL,          -- deezer (automatique) ou redaction
    external_id VARCHAR(40)  NULL UNIQUE,       -- identifiant Deezer de la sortie
    status      VARCHAR(12)  NOT NULL DEFAULT 'published',
    created_at  TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_artist_events_date ON artist_events (event_date);
