-- Distinctions officielles Cauri Charts : rares, mensuelles, tirées des classements mensuels publiés. Ajout seulement.
-- Le numéro de la distinction (N° 0001…) est l'identifiant : il ne se réutilise jamais.
CREATE TABLE IF NOT EXISTS award_distinctions (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chart_run_id INTEGER      NOT NULL REFERENCES chart_runs(id),
    scope        VARCHAR(3)   NOT NULL,          -- WA (Afrique de l'Ouest) ou code pays
    period_key   VARCHAR(10)  NOT NULL,          -- 2026-10
    rank         SMALLINT     NOT NULL,
    track_id     INTEGER      NULL REFERENCES tracks(id),
    artist_id    INTEGER      NOT NULL REFERENCES artists(id),
    artist_name  VARCHAR(150) NOT NULL,
    title        VARCHAR(200) NULL,
    chart_label  VARCHAR(80)  NOT NULL,          -- « Top 20 · Afrique de l'Ouest »
    stats        TEXT         NOT NULL DEFAULT '{}',  -- {last, peak, weeks} tirés de chart_entries
    photo_url    VARCHAR(500) NULL,
    image_name   VARCHAR(60)  NULL,              -- media/distinctions/<id>.jpg
    status       VARCHAR(10)  NOT NULL DEFAULT 'new',  -- new, sent
    sent_at      TIMESTAMP(0) NULL,
    created_at   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uq_distinction_rank UNIQUE (chart_run_id, rank)
);
-- Rareté : un titre n'est distingué qu'une fois par classement (Afrique de l'Ouest ou pays)
CREATE UNIQUE INDEX IF NOT EXISTS uq_distinction_track_scope ON award_distinctions (track_id, scope) WHERE track_id IS NOT NULL;
