-- Monthly Show : vote du public (seule source officielle des votes ; ne touche jamais aux classements). Ajout seulement.
-- Comptes du public par lien de connexion envoyé par e-mail ; une voix par compte et par vote ; codes secrets ; parrainage.
CREATE TABLE IF NOT EXISTS show_accounts (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(190) NOT NULL UNIQUE,
    pseudo        VARCHAR(40)  NOT NULL,
    country_code  VARCHAR(2)   NULL,
    display_ok    SMALLINT     NOT NULL DEFAULT 0,     -- accord pour afficher le pseudo à l'écran
    ref           VARCHAR(12)  NOT NULL UNIQUE,         -- code de parrainage personnel
    referred_by   INTEGER      NULL REFERENCES show_accounts(id),
    ip_hash       VARCHAR(64)  NOT NULL,
    verified_at   TIMESTAMP(0) NULL,
    created_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS show_login_tokens (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash    VARCHAR(64)  NOT NULL UNIQUE,
    email         VARCHAR(190) NOT NULL,
    data          TEXT         NOT NULL DEFAULT '{}',   -- pseudo, pays, accord, parrain (JSON) pour un premier compte
    expires_at    TIMESTAMP(0) NOT NULL,
    used_at       TIMESTAMP(0) NULL,
    ip_hash       VARCHAR(64)  NOT NULL,
    created_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS show_polls (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_key      VARCHAR(10)  NOT NULL,
    slug          VARCHAR(60)  NOT NULL,
    kind          VARCHAR(12)  NOT NULL,                -- presence, pronostic, choix, sondage
    title         VARCHAR(200) NOT NULL,
    options       TEXT         NOT NULL DEFAULT '[]',   -- [{"key","label","sub","image"}]
    status        VARCHAR(10)  NOT NULL DEFAULT 'brouillon',  -- brouillon, ouvert, scelle, ferme
    answer        VARCHAR(60)  NULL,                    -- bonne réponse d'un pronostic (après révélation)
    sort_order    SMALLINT     NOT NULL DEFAULT 0,
    opened_at     TIMESTAMP(0) NULL,
    closed_at     TIMESTAMP(0) NULL,
    created_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uq_show_poll UNIQUE (show_key, slug)
);
CREATE TABLE IF NOT EXISTS show_votes (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id       INTEGER      NOT NULL REFERENCES show_polls(id),
    account_id    INTEGER      NOT NULL REFERENCES show_accounts(id),
    option_key    VARCHAR(60)  NOT NULL,
    ip_hash       VARCHAR(64)  NOT NULL,
    flagged       SMALLINT     NOT NULL DEFAULT 0,      -- voix suspecte : mise de côté, jamais supprimée
    created_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uq_show_vote UNIQUE (poll_id, account_id)
);
CREATE INDEX IF NOT EXISTS ix_show_votes_poll ON show_votes (poll_id, option_key);
CREATE TABLE IF NOT EXISTS show_codes (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_key      VARCHAR(10)  NOT NULL,
    code          VARCHAR(12)  NOT NULL,
    status        VARCHAR(10)  NOT NULL DEFAULT 'prepare',  -- prepare, actif, expire
    activated_at  TIMESTAMP(0) NULL,
    created_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uq_show_code UNIQUE (show_key, code)
);
CREATE TABLE IF NOT EXISTS show_code_entries (
    code_id       INTEGER      NOT NULL REFERENCES show_codes(id),
    account_id    INTEGER      NOT NULL REFERENCES show_accounts(id),
    created_at    TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
    PRIMARY KEY (code_id, account_id)
);
