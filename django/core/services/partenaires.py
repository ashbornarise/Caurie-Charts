def dossier(semaine: str, partenaire: dict) -> dict:
    """{nom de fichier: octets} de l'édition : PDF, Excel, visuels TV (.zip)."""
    pays = [p for p in (partenaire.get("pays") or "").split(",") if p]
    d = donnees(semaine, pays)
    if not d["perimetres"]:
        return {}
    z = io.BytesIO()
    with zipfile.ZipFile(z, "w", zipfile.ZIP_STORED) as f:   # PNG déjà compressés
        for nom, data in visuels(d):
            f.writestr(nom, data)
    base = f"cauri-charts-{semaine}"
    return {f"{base}.pdf": pdf(d, partenaire["nom"]), f"{base}.xlsx": excel(d), f"{base}-visuels-tv.zip": z.getvalue(),
            "_donnees": d}


TYPES = {".pdf": "application/pdf", ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
         ".zip": "application/zip", ".png": "image/png"}


def _depose(jeton: str, semaine: str, nom: str, data: bytes) -> str:
    from core import storage
    chemin = f"partenaires/{_dossier_blob(jeton)}/{semaine}/{nom}"
    if storage.blob_token():
        return storage.blob_put(chemin, data, TYPES.get(Path(nom).suffix, "application/octet-stream"))
    local = storage.upload_path(chemin)
    local.parent.mkdir(parents=True, exist_ok=True)
    local.write_bytes(data)
    return "/media/" + chemin


def _mail(partenaire: dict, semaine: str, fichiers: dict, liens: dict, d: dict, a: list[str]) -> bool:
    from email.message import EmailMessage  # noqa: F401  (type des pièces jointes)
    from core import mail
    periode = f"du {_date_fr(d['periode'][0])} au {_date_fr(d['periode'][1])}" if d["periode"] else ""
    faits_txt = "\n\n".join(f"{p['nom']}\n" + "\n".join("• " + f for f in p["faits"]) for p in d["perimetres"])
    zip_nom = next(n for n in liens if n.endswith(".zip"))
    texte = (f"Bonjour,\n\nLes classements officiels Cauri Charts de la semaine {semaine[-2:]} ({periode}) viennent de paraître. "
             f"Voici votre dossier de diffusion.\n\n{faits_txt}\n\n"
             f"En pièces jointes : le dossier PDF et le tableau Excel complet.\n\n"
             f"Visuels prêts pour l'antenne (1920 x 1080) : {liens[zip_nom]}\n\n"
             f"Votre espace réservé, avec toutes les éditions : {lien(partenaire['jeton'])}\n\n"
             "Merci de mentionner « Source : Cauri Charts » à l'antenne.\n\nL'équipe Cauri Charts")
    ok = True
    for dest in a:
        msg = mail._message(dest, f"Cauri Charts · classements de la semaine {semaine[-2:]} ({periode})", texte)
        msg.add_alternative(mail.habiller(texte), subtype="html")
        for nom, data in fichiers.items():
            if nom.endswith(".pdf"):
                msg.add_attachment(data, maintype="application", subtype="pdf", filename=nom)
            elif nom.endswith(".xlsx"):
                msg.add_attachment(data, maintype="application",
                                   subtype="vnd.openxmlformats-officedocument.spreadsheetml.sheet", filename=nom)
        ok = mail._send(msg, dest, "dossier partenaire") and ok
    return ok


def envoyer(semaine: str, partenaire_id: int | None = None, a: list[str] | None = None, forcer: bool = False) -> list[str]:
    """Envoie l'édition de la semaine aux partenaires actifs qui ne l'ont pas reçue. a : destinataires de test
    (l'édition n'est alors pas marquée comme envoyée)."""
    assure_tables()
    bilan = []
    sql = "SELECT * FROM partenaires_acces WHERE actif = 1" + (" AND id = ?" if partenaire_id else "")
    for p in db.all(sql, [partenaire_id] if partenaire_id else []):
        deja = db.one("SELECT * FROM partenaires_editions WHERE partenaire_id = ? AND semaine = ?", [p["id"], semaine])
        if deja and deja["envoye_le"] and not a and not forcer:
            bilan.append(f"{p['nom']} : semaine {semaine} déjà envoyée")
            continue
        fichiers = dossier(semaine, p)
        d = fichiers.pop("_donnees", None)
        if not fichiers:
            bilan.append(f"{p['nom']} : rien de publié pour la semaine {semaine}")
            continue
        liens = {nom: _depose(p["jeton"], semaine, nom, data) for nom, data in fichiers.items()}
        dest = a or [e for e in (p["emails"] or "").split(",") if e]
        ok = _mail(p, semaine, fichiers, liens, d, dest)
        champs = {"fichiers": json.dumps(liens, ensure_ascii=False)}
        if not a and ok:
            champs.update(envoye_le=now_utc(), destinataires=",".join(dest))
        if deja:
            db.update("partenaires_editions", champs, "id = :id", {"id": deja["id"]})
        else:
            db.insert("partenaires_editions", {"partenaire_id": p["id"], "semaine": semaine, **champs})
        bilan.append(f"{p['nom']} : semaine {semaine} {'envoyée' if ok else 'ÉCHEC de l’envoi'} à {', '.join(dest)}"
                     + (" (essai)" if a else ""))
    return bilan
