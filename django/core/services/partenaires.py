def excel(d: dict) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    wb = Workbook()
    ws = wb.active
    ws.title = "Résumé"
    tete = Font(bold=True, color="FFFFFF")
    fond = PatternFill("solid", fgColor="7C3AED")
    ws.append([f"Cauri Charts · semaine {d['semaine']}" + (f" (du {_date_fr(d['periode'][0])} au {_date_fr(d['periode'][1])})"
                                                          if d["periode"] else "")])
    ws["A1"].font = Font(bold=True, size=14)
    ws.append(["Source : Cauri Charts, la référence de la musique ouest-africaine (cauricharts.com)"])
    for p in d["perimetres"]:
        ws.append([])
        ws.append([p["nom"]])
        ws.cell(ws.max_row, 1).font = Font(bold=True, size=12)
        for f in p["faits"]:
            ws.append(["• " + f])
    ws.column_dimensions["A"].width = 110
    for p in d["perimetres"]:
        for c in p["classements"]:
            nom = re.sub(r"[\[\]:*?/\\]", "", f"{p['code']} {c['nom'].replace('Top ', '')}")[:31]
            f = wb.create_sheet(nom)
            entetes = (["Rang", "Évolution", "Artiste", "Titres classés", "Score", "Semaines", "Meilleur rang"] if c["artistes"]
                       else ["Rang", "Évolution", "Titre", "Artiste", "Featuring", "Pays", "Score", "Semaines", "Meilleur rang"])
            f.append(entetes)
            for i in range(1, len(entetes) + 1):
                f.cell(1, i).font, f.cell(1, i).fill = tete, fond
                f.cell(1, i).alignment = Alignment(horizontal="center")
            for l in c["lignes"]:
                f.append([l["rang"], _mouvement(l), l["artiste"], l["titres"], round(l["score"], 2), l["semaines"], l["meilleur"]]
                         if c["artistes"] else
                         [l["rang"], _mouvement(l), l["titre"], l["artiste"], l["feat"], l["pays"], round(l["score"], 2),
                          l["semaines"], l["meilleur"]])
            for col, w in zip("ABCDEFGHI", ([7, 11, 30, 14, 12, 10, 14] if c["artistes"] else [7, 11, 36, 26, 22, 7, 12, 10, 14])):
                f.column_dimensions[col].width = w
            f.freeze_panes = "A2"
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()


