# ---------------------------------------------------------------- tables, partenaires

def assure_tables() -> None:
    db.run("""CREATE TABLE IF NOT EXISTS partenaires_acces (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nom VARCHAR(120) NOT NULL, emails TEXT NOT NULL,
        jeton VARCHAR(64) NOT NULL UNIQUE, pays VARCHAR(120) NOT NULL DEFAULT '', actif SMALLINT NOT NULL DEFAULT 1,
        cree_le TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP)""")
    db.run("""CREATE TABLE IF NOT EXISTS partenaires_editions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, partenaire_id INTEGER NOT NULL REFERENCES partenaires_acces(id),
        semaine VARCHAR(10) NOT NULL, fichiers TEXT NOT NULL, envoye_le TIMESTAMP(0) NULL, destinataires TEXT NULL,
        cree_le TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP, CONSTRAINT uq_part_ed UNIQUE (partenaire_id, semaine))""")


def ajouter(nom: str, emails: list[str], pays: list[str]) -> dict:
    assure_tables()
    jeton = secrets.token_urlsafe(24)
    pid = db.insert("partenaires_acces", {"nom": nom[:120], "emails": ",".join(e.strip() for e in emails if e.strip()),
                                          "jeton": jeton, "pays": ",".join(p.strip().upper() for p in pays if p.strip())})
    return {"id": pid, "jeton": jeton, "lien": lien(jeton)}


def lien(jeton: str) -> str:
    return f"{(env.get('APP_URL', '') or SITE).rstrip('/')}/partenaire/{jeton}"


def par_jeton(jeton: str) -> dict | None:
    if not jeton or not re.fullmatch(r"[A-Za-z0-9_-]{20,64}", jeton):
        return None
    try:
        return db.one("SELECT * FROM partenaires_acces WHERE jeton = ? AND actif = 1", [jeton])
    except Exception:  # noqa: BLE001 — table pas encore créée
        return None


def editions(partenaire_id: int) -> list[dict]:
    rows = db.all("SELECT * FROM partenaires_editions WHERE partenaire_id = ? ORDER BY semaine DESC", [partenaire_id])
    for r in rows:
        r["fichiers"] = json.loads(r["fichiers"] or "{}")
    return rows


def _dossier_blob(jeton: str) -> str:
    """Dossier des fichiers : dérivé du jeton, sans le révéler."""
    return hashlib.sha256(("cauri-partenaire:" + jeton).encode()).hexdigest()[:24]


# ---------------------------------------------------------------- données de la semaine

def _codes() -> list[str]:
    charts = conf.get("charts") or {}
    return ORDRE + [c for c, cfg in charts.items() if cfg.get("genre")]


def _nom(code: str, perimetre: str) -> str:
    if code == "prime":
        return "Top 20 des titres" if perimetre == "WA" else "Top des titres"
    return (conf.get(f"charts.{code}") or {}).get("name", code)


def _date_fr(d: str) -> str:
    j = date.fromisoformat(str(d)[:10])
    return f"{'1er' if j.day == 1 else j.day} {MOIS[j.month - 1]} {j.year}"


def donnees(semaine: str, pays: list[str]) -> dict:
    """Classements publiés de la semaine : {perimetres: [{code, nom, classements: [{code, nom, lignes}], faits}], periode}."""
    from core import repos
    perimetres, periode = [], None
    for code_pays in [p for p in pays if p != "WA"] + ["WA"]:
        cid = None
        if code_pays != "WA":
            c = db.one("SELECT id FROM countries WHERE code = ?", [code_pays])
            if not c:
                continue
            cid = int(c["id"])
        classements = []
        for code in _codes():
            run = repos.run(cid, "prime-wa" if (cid is None and code == "prime") else code, "week", semaine)
            if not run:
                continue
            periode = periode or (run["period_start"], run["period_end"])
            lignes = []
            for e in repos.entries(int(run["id"])):
                lignes.append({
                    "rang": int(e["position"]), "precedent": e.get("previous_position"), "meilleur": e.get("peak_position"),
                    "semaines": e.get("weeks_on_chart"), "titre": e.get("title") if e.get("track_id") else None,
                    "artiste": e.get("artist_name") or "", "feat": e.get("featuring") or "", "pays": e.get("artist_country") or "",
                    "score": float(e.get("score") or 0), "titres": e.get("sources_count") if not e.get("track_id") else None,
                    "image": e.get("cover_url") or e.get("artist_image") or "",
                })
            classements.append({"code": code, "nom": _nom(code, code_pays), "artistes": run.get("kind") == "artists",
                                "lignes": lignes})
        if classements:
            perimetres.append({"code": code_pays, "nom": NOMS_PAYS.get(code_pays, code_pays), "classements": classements,
                               "faits": faits(classements)})
    return {"semaine": semaine, "periode": periode, "perimetres": perimetres}


def _e(n: int) -> str:
    return f"{n}re" if n == 1 else f"{n}e"


def _libelle(l: dict) -> str:
    return f"« {l['titre']} » de {l['artiste']}" if l.get("titre") else l["artiste"]


def faits(classements: list[dict]) -> list[str]:
    """Faits marquants, calculés seulement à partir des classements publiés."""
    par = {c["code"]: c["lignes"] for c in classements}
    out = []
    top = par.get("prime") or []
    if top:
        n1 = top[0]
        if n1["precedent"] == 1:
            out.append(f"{_libelle(n1)} reste n°1 ({n1['semaines']} semaines au classement).")
        elif n1["precedent"]:
            out.append(f"Nouveau n°1 : {_libelle(n1)}, qui était {_e(n1['precedent'])} la semaine passée.")
        else:
            out.append(f"Entrée directe à la 1re place : {_libelle(n1)}.")
        montees = [l for l in top[1:] if l["precedent"] and l["precedent"] > l["rang"]]
        if montees:
            m = max(montees, key=lambda l: l["precedent"] - l["rang"])
            out.append(f"Plus forte progression : {_libelle(m)}, de la {_e(m['precedent'])} à la {_e(m['rang'])} place "
                       f"(+{m['precedent'] - m['rang']}).")
        entrees = [l for l in top if not l["precedent"] and (l["semaines"] or 1) <= 1]
        if entrees:
            e = min(entrees, key=lambda l: l["rang"])
            out.append(f"Meilleure entrée : {_libelle(e)}, directement {_e(e['rang'])}." if e["rang"] > 1 else "")
    if par.get("icon"):
        a = par["icon"][0]
        n = a["titres"] or 1
        out.append(f"Artiste de la semaine : {a['artiste']} (points cumulés sur {n} titre{'s' if n > 1 else ''}).")
    if par.get("saison"):
        out.append(f"En tête de la saison : {par['saison'][0]['artiste']}.")
    for c in classements:
        if c["code"].startswith("g-") and c["lignes"]:
            out.append(f"N°1 {c['nom'].replace('Top ', '')} : {_libelle(c['lignes'][0])}.")
    return [f for f in out if f]


def _mouvement(l: dict) -> str:
    if not l["precedent"]:
        return "NOUVEAU" if (l["semaines"] or 1) <= 1 else "RETOUR"
    d = l["precedent"] - l["rang"]
    return f"+{d}" if d > 0 else (str(d) if d < 0 else "=")


